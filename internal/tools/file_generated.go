package tools

import (
	"bytes"
	"strings"
)

// generatedHeadLines is the number of leading lines in which a generator
// writes its marker.
const generatedHeadLines = 5

// isGenerated reports whether the first lines of a file carry a marker of a
// code generator, and names the marker. The guard in write is a safety net
// against overwriting generator output; it is not a policy.
func isGenerated(head []byte) (marker string, ok bool) {
	lines := bytes.SplitN(head, []byte("\n"), generatedHeadLines+1)
	if len(lines) > generatedHeadLines {
		lines = lines[:generatedHeadLines]
	}
	for _, l := range lines {
		line := string(l)
		switch {
		case strings.Contains(line, "@generated"):
			return "@generated", true
		case strings.Contains(line, "Code generated") && strings.Contains(line, "DO NOT EDIT"):
			// Go and sqlc headers: "Code generated by <tool>. DO NOT EDIT."
			return "Code generated ... DO NOT EDIT", true
		case strings.Contains(line, "Generated by the protocol buffer compiler"):
			return "Generated by the protocol buffer compiler", true
		}
	}
	return "", false
}
