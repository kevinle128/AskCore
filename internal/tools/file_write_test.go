func TestWriteCreatesParentsAtomically(t *testing.T) {
	h := newFileHarness(t, nil)

	res := h.mustRun("write", map[string]any{"path": "deep/er/new.txt", "content": "hello\n"})

	assert.Equal(t, "Successfully wrote to deep/er/new.txt", resultText(t, res))
	assert.Equal(t, "hello\n", h.content("deep/er/new.txt"))
	entries, err := os.ReadDir(h.path("deep/er"))
	require.NoError(t, err)
	require.Len(t, entries, 1, "no temp file stays behind")
	assert.Equal(t, "new.txt", entries[0].Name())
	info, err := os.Stat(h.path("deep/er"))
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o755), info.Mode().Perm())
	info, err = os.Stat(h.path("deep/er/new.txt"))
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o644), info.Mode().Perm())
}

func TestWriteDetailsCarryDiffAndLocation(t *testing.T) {
	h := newFileHarness(t, nil)

	res := h.mustRun("write", map[string]any{"path": "a.txt", "content": "one\n"})
	d := resultDetails(t, res)
	assert.Equal(t, protocol.ToolKindEdit, d.Kind)
	assert.Equal(t, h.path("a.txt"), d.Path)
	require.NotNil(t, d.Diff)
	assert.Equal(t, "", d.Diff.OldText)
	assert.Equal(t, "one\n", d.Diff.NewText)
	assert.Equal(t, []protocol.ToolLocation{{Path: h.path("a.txt"), Line: 1}}, d.Locations)

	res = h.mustRun("write", map[string]any{"path": "a.txt", "content": "two\n"})
	d = resultDetails(t, res)
	assert.Equal(t, "one\n", d.Diff.OldText)
	assert.Equal(t, "two\n", d.Diff.NewText)
}

func TestWriteSetsExecutableBitForShebang(t *testing.T) {
	h := newFileHarness(t, nil)

	h.mustRun("write", map[string]any{"path": "run.sh", "content": "#!/bin/sh\necho hi\n"})
	info, err := os.Stat(h.path("run.sh"))
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o755), info.Mode().Perm())

	// An existing private file keeps its read bits and gains only the matching
	// execute bit.
	p := h.put("private.sh", "old\n")
	require.NoError(t, os.Chmod(p, 0o600))
	h.mustRun("write", map[string]any{"path": "private.sh", "content": "#!/bin/sh\n"})
	info, err = os.Stat(p)
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o700), info.Mode().Perm())

	h.mustRun("write", map[string]any{"path": "plain.txt", "content": "no shebang\n"})
	info, err = os.Stat(h.path("plain.txt"))
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o644), info.Mode().Perm())
}

func TestWriteRefusesGeneratedFile(t *testing.T) {
	h := newFileHarness(t, nil)
	original := "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage api\n"
	h.put("api.pb.go", original)

	_, err := h.run("write", map[string]any{"path": "api.pb.go", "content": "package api\n"})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "api.pb.go")
	assert.Contains(t, err.Error(), "Code generated")
	assert.Equal(t, original, h.content("api.pb.go"))
}

func TestWriteChecksAllFiveHeaderLinesForGeneratorMarkers(t *testing.T) {
	h := newFileHarness(t, nil)
	original := strings.Repeat("x", 5000) + "\n2\n3\n4\n// @generated\nbody\n"
	h.put("generated.txt", original)
	_, err := h.run("write", map[string]any{"path": "generated.txt", "content": "replacement"})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "@generated")
	assert.Equal(t, original, h.content("generated.txt"))
}

func TestWriteMayCreateFileWithGeneratedHeader(t *testing.T) {
	h := newFileHarness(t, nil)

	h.mustRun("write", map[string]any{"path": "gen.go", "content": "// Code generated by x. DO NOT EDIT.\npackage x\n"})

	assert.True(t, strings.HasPrefix(h.content("gen.go"), "// Code generated"))
}

func TestWriteRecordsStateSoNextEditPasses(t *testing.T) {
	h := newFileHarness(t, nil)
	h.put("a.txt", "old\n")
	h.mustRun("read", map[string]any{"path": "a.txt"})

	h.mustRun("write", map[string]any{"path": "a.txt", "content": "alpha\nbeta\n"})
	h.mustRun("edit", edit("a.txt", "beta", "BETA"))

	assert.Equal(t, "alpha\nBETA\n", h.content("a.txt"))
}

func TestWriteThroughSymlinkKeepsLink(t *testing.T) {
	h := newFileHarness(t, nil)
	target := h.put("real.txt", "old\n")
	require.NoError(t, os.Symlink(target, h.path("link.txt")))

	h.mustRun("write", map[string]any{"path": "link.txt", "content": "new\n"})

	assert.Equal(t, "new\n", h.content("real.txt"))
	info, err := os.Lstat(h.path("link.txt"))
	require.NoError(t, err)
	assert.NotZero(t, info.Mode()&os.ModeSymlink)
}

func TestWriteIntoDirectoryPathFails(t *testing.T) {
	h := newFileHarness(t, nil)
	require.NoError(t, os.Mkdir(h.path("d"), 0o755))

	_, err := h.run("write", map[string]any{"path": "d", "content": "x"})

	require.Error(t, err)
	assert.Contains(t, filepath.Base(err.Error()), "d")
}
