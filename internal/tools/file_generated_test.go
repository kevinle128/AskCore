package tools

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestIsGenerated(t *testing.T) {
	cases := []struct {
		name   string
		head   string
		marker string
		ok     bool
	}{
		{"go generated header", "// Code generated by mockgen. DO NOT EDIT.\npackage x\n", "Code generated ... DO NOT EDIT", true},
		{"at generated", "/* @generated */\nbody\n", "@generated", true},
		{"protoc header", "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n", "Generated by the protocol buffer compiler", true},
		{"sqlc header", "// Code generated by sqlc. DO NOT EDIT.\n// versions:\n", "Code generated ... DO NOT EDIT", true},
		{"code generated without do-not-edit", "// Code generated by hand once\n", "", false},
		{"marker on line five", "1\n2\n3\n4\n// @generated\n", "@generated", true},
		{"marker on line six", "1\n2\n3\n4\n5\n// @generated\n", "", false},
		{"plain file", "package x\n\nfunc main() {}\n", "", false},
		{"empty", "", "", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			marker, ok := isGenerated([]byte(c.head))
			assert.Equal(t, c.ok, ok)
			assert.Equal(t, c.marker, marker)
		})
	}
}

func TestIsGeneratedLooksOnlyAtTheHead(t *testing.T) {
	head := strings.Repeat("x\n", 10) + "// Code generated by x. DO NOT EDIT.\n"
	_, ok := isGenerated([]byte(head))
	assert.False(t, ok)
}
