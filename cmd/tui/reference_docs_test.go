const (
	updateDocsEnv  = "ASK_UPDATE_DOCS"
	docsHeader     = "<!-- Generated by TestReferenceDocs in cmd/tui/reference_docs_test.go. Do not edit by hand. -->"
	updateDocsHint = "run ASK_UPDATE_DOCS=1 go test -run '^TestReferenceDocs$' ./cmd/tui"
)

// TestReferenceDocs keeps docs/reference in step with the code. It renders the
// tool and provider references from the same sources the product uses. With
// ASK_UPDATE_DOCS=1 it writes the files. Without it, it fails when a file
// differs, so a change to a tool or a model cannot leave stale docs.
func TestReferenceDocs(t *testing.T) {
	docs := map[string]string{
		"tools.md":     renderToolsDoc(t),
		"providers.md": renderProvidersDoc(),
	}
	names := make([]string, 0, len(docs))
	for name := range docs {
		names = append(names, name)
	}
	slices.Sort(names)

	update := os.Getenv(updateDocsEnv) == "1"
	for _, name := range names {
		path := filepath.Join("..", "..", "docs", "reference", name)
		want := docs[name]
		if update {
			require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
			require.NoError(t, os.WriteFile(path, []byte(want), 0o644))
			continue
		}
		got, err := os.ReadFile(path)
		require.NoError(t, err, "cannot read docs/reference/%s; %s", name, updateDocsHint)
		if string(got) != want {
			t.Errorf("docs/reference/%s is out of date (%s).\n%s\n%s",
				name, firstDifference(string(got), want), "To fix it:", updateDocsHint)
		}
	}
}

// firstDifference names the first line where the file and the render differ.
func firstDifference(got, want string) string {
	g, w := strings.Split(got, "\n"), strings.Split(want, "\n")
	for i := 0; i < max(len(g), len(w)); i++ {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl != wl {
			return fmt.Sprintf("first difference at line %d: file has %q, code gives %q", i+1, gl, wl)
		}
	}
	return "no line differs"
}

// sessionRegistry registers the tools the same way newNativeAgentOn does, so
// the reference lists what a real session has. The job table only has to
// exist: no tool runs here.
func sessionRegistry(t *testing.T) *tools.Registry {
	t.Helper()
	jt := jobs.New(jobs.Options{Clock: sandbox.SystemClock})
	t.Cleanup(func() { require.NoError(t, jt.Close()) })
	reg := &tools.Registry{}
	for _, tl := range sessionTools(jt, tools.NewFileState(), func() []string { return nil }) {
		require.NoError(t, reg.Register(tl, tools.SourceInfo{Kind: tools.SourceBuiltin}))
	}
	return reg
}

func renderToolsDoc(t *testing.T) string {
	t.Helper()
	snap := sessionRegistry(t).Snapshot()
	decls := snap.Decls()
	slices.SortFunc(decls, func(a, b protocol.ToolDecl) int { return strings.Compare(a.Name, b.Name) })

	var b strings.Builder
	b.WriteString(docsHeader + "\n\n# Built-in tools\n\n")
	b.WriteString("Every Ask session registers these tools.\n")
	for _, d := range decls {
		tl, _, ok := snap.Lookup(d.Name)
		require.True(t, ok, "tool %q is in Decls but not in Lookup", d.Name)

		b.WriteString("\n## `" + d.Name + "`\n\n")
		if d.Name == demoToolName {
			b.WriteString("This is a demo tool. The faux demo provider calls it. It is registered in every session.\n\n")
		}
		if pc, ok := tl.(tools.PromptContributor); ok {
			if s := strings.TrimSpace(pc.PromptSnippet()); s != "" {
				b.WriteString("Prompt snippet: " + s + "\n\n")
			}
		}
		b.WriteString("Description:\n\n" + quote(d.Description) + "\n\n")
		b.WriteString("Parameters:\n\n")
		b.WriteString(renderParameters(t, d))
		if pc, ok := tl.(tools.PromptContributor); ok {
			var gs []string
			for _, g := range pc.PromptGuidelines() {
				if g = strings.TrimSpace(g); g != "" {
					gs = append(gs, g)
				}
			}
			if len(gs) > 0 {
				b.WriteString("\nGuidelines:\n\n")
				for _, g := range gs {
					b.WriteString("- " + oneLine(g) + "\n")
				}
			}
		}
	}
	return b.String()
}

// demoToolName is the tool that exists for the faux demo provider.
const demoToolName = "echo"

// schemaProp is the part of a JSON-schema property that the reference shows.
type schemaProp struct {
	Type        any             `json:"type"`
	Description string          `json:"description"`
	Enum        []any           `json:"enum"`
	Items       *schemaProp     `json:"items"`
	Default     json.RawMessage `json:"default"`
}

func renderParameters(t *testing.T, d protocol.ToolDecl) string {
	t.Helper()
	var s struct {
		Properties map[string]schemaProp `json:"properties"`
		Required   []string              `json:"required"`
	}
	require.NoError(t, json.Unmarshal(d.Parameters, &s), "parameters of %q", d.Name)
	if len(s.Properties) == 0 {
		return "This tool takes no parameters.\n"
	}
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	slices.Sort(names)
	var b strings.Builder
	for _, n := range names {
		p := s.Properties[n]
		req := "optional"
		if slices.Contains(s.Required, n) {
			req = "required"
		}
		line := fmt.Sprintf("- `%s` (%s, %s)", n, typeName(p), req)
		if len(p.Enum) > 0 {
			vals := make([]string, len(p.Enum))
			for i, v := range p.Enum {
				vals[i] = fmt.Sprintf("`%v`", v)
			}
			line += " One of: " + strings.Join(vals, ", ") + "."
		}
		if len(p.Default) > 0 {
			line += " Default: `" + string(p.Default) + "`."
		}
		if p.Description != "" {
			line += ": " + oneLine(p.Description)
		}
		b.WriteString(line + "\n")
	}
	return b.String()
}

func typeName(p schemaProp) string {
	var name string
	switch v := p.Type.(type) {
	case string:
		name = v
	case []any:
		parts := make([]string, len(v))
		for i, x := range v {
			parts[i] = fmt.Sprint(x)
		}
		name = strings.Join(parts, " or ")
	default:
		name = "any"
	}
	if name == "array" && p.Items != nil {
		name += " of " + typeName(*p.Items)
	}
	return name
}

// oneLine joins the lines of a text so it fits one list item.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// quote renders a text as a block quote and keeps its line breaks.
func quote(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight("> "+l, " ")
	}
	return strings.Join(lines, "\n")
}

func renderProvidersDoc() string {
	models := providers.AvailableModels()
	byProvider := map[string][]providers.Model{}
	for _, m := range models {
		byProvider[m.Provider] = append(byProvider[m.Provider], m)
	}
	ids := make([]string, 0, len(byProvider))
	for id := range byProvider {
		ids = append(ids, id)
	}
	slices.Sort(ids)

	var b strings.Builder
	b.WriteString(docsHeader + "\n\n# Providers and models\n\n")
	b.WriteString("These are the providers and models in the compiled model catalog.\n")
	for _, id := range ids {
		ms := byProvider[id]
		slices.SortFunc(ms, func(a, c providers.Model) int {
			if r := strings.Compare(a.ID, c.ID); r != 0 {
				return r
			}
			return strings.Compare(string(a.API), string(c.API))
		})
		rec, hasRec := providers.RecommendedModel(id)
		b.WriteString("\n## `" + id + "`\n\n")
		if hasRec {
			b.WriteString("Recommended model: `" + rec.ID + "` on `" + string(rec.API) + "`.\n\n")
		} else {
			b.WriteString("This provider has no recommended model.\n\n")
		}
		for _, m := range ms {
			b.WriteString("### `" + m.ID + "` on `" + string(m.API) + "`\n\n")
			b.WriteString("- Display name: " + m.Name + "\n")
			b.WriteString("- API format: `" + string(m.API) + "`\n")
			b.WriteString("- Context window: " + strconv.Itoa(m.ContextWindow) + " tokens\n")
			b.WriteString("- Maximum output: " + strconv.Itoa(m.MaxTokens) + " tokens\n")
			b.WriteString("- Reasoning: " + yesNo(m.Reasoning) + "\n")
			b.WriteString("- Input kinds: " + strings.Join(m.Input, ", ") + "\n")
			b.WriteString("- Recommended: " + yesNo(hasRec && rec.ID == m.ID && rec.API == m.API) + "\n\n")
		}
	}
	b.WriteString("## `faux`\n\n")
	b.WriteString("The faux provider is a scripted demo. It is not in the catalog above.\n")
	b.WriteString("The leader, `ask acp` and the in-process TUI list it only when `ASK_FAUX=1` is set.\n")
	b.WriteString("`ask -p` uses it as the default provider.\n")
	return b.String()
}
