const puppeteer = require('puppeteer-core');
(async () => {
  const b = await puppeteer.launch({executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new'});
  const p = await b.newPage(); const errs = [];
  p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.setViewport({width: 1400, height: 1000});
  await p.goto('file://' + process.argv[2]);
  const txt = () => p.$eval('#term', t => t.innerText);
  const ok = (name, c) => console.log((c ? 'PASS ' : 'FAIL ') + name);
  const sleep = ms => new Promise(r => setTimeout(r, ms));
  const rowOf = async s => (await p.$$('#term .r')).find ? (await Promise.all((await p.$$('#term .r')).map(async h => [h, await h.evaluate(e => e.textContent)]))).find(([, t]) => t.includes(s))[0] : null;
  await p.click('#term');
  let r = await rowOf('Ran go test ./...'); await r.click(); await sleep(50);
  ok('click tool header opens viewer', (await txt()).includes('← back'));
  await p.keyboard.press('Escape'); await sleep(50);
  ok('Esc returns', !(await txt()).includes('← back') && (await txt()).includes('j/k select'));
  await p.mouse.move(5, 5); await sleep(50);
  ok('selected collapsed tool shows ›', (await txt()).includes('› Ran go test ./...'));
  ok('unselected steps keep ◆', (await txt()).includes('◆ Ran seq 1 40') && (await txt()).includes('◆ Edited parser.go'));
  await p.keyboard.press('ArrowRight'); await sleep(30);
  ok('→ expands to Expanded', (await txt()).includes('e fold: expanded') && (await txt()).includes('$ go test ./...') && (await txt()).includes('⌄ Ran go test'));
  ok('expanded tool: ┃ on every row, no shade', await p.evaluate(() => { const r = [...document.querySelectorAll('#term .r')].filter(r => r.dataset.b == askProto.state.sel); return r.length > 3 && r.every(x => x.textContent.startsWith('┃') && !x.classList.contains('sel')); }));
  await p.keyboard.press('ArrowLeft'); await sleep(30);
  ok('← collapses', (await txt()).includes('e fold: collapsed') && !(await txt()).includes('$ go test ./...'));
  await p.keyboard.press('l'); await sleep(30); const lx = (await txt()).includes('e fold: expanded');
  await p.keyboard.press('h'); await sleep(30);
  ok('l and h do the same', lx && (await txt()).includes('e fold: collapsed'));
  await p.keyboard.press('j'); await sleep(30);
  ok('non-foldable reply selected: no › and steps keep ◆', !(await txt()).includes('›') && (await txt()).includes('◆ Ran go test ./...'));
  await p.keyboard.press('ArrowRight'); await sleep(30);
  const rr = await p.evaluate(() => [...document.querySelectorAll('#term .r')].filter(r => r.dataset.b == askProto.state.sel).map(r => ({t: r.textContent, sh: r.classList.contains('sel')})));
  const content = rr.filter(x => x.t.trim());
  ok('reply selected: every row has ┃ gutter incl. usage row, none shaded', content.length >= 3 && content.every(x => x.t.startsWith('┃') && !x.sh) && content.some(x => x.t.includes('$0.006')));
  ok('→ on reply changes nothing', !(await txt()).includes('$ go test') && (await txt()).includes('shall I fix'));
  await p.keyboard.press('k'); await sleep(30);
  const hb = await p.evaluate(() => { const e = [...document.querySelectorAll('#term .r')].find(r => r.textContent.includes('lint-guard')); const q = e.getBoundingClientRect(); return {x: q.x + 200, y: q.y + q.height / 2}; });
  await p.mouse.move(hb.x, hb.y); await sleep(50);
  ok('hover on collapsed hook shows ›', (await txt()).includes('›  PreToolUse hook (project/lint-guard)'));
  await p.mouse.move(5, 5); await sleep(50);
  ok('hover leaves: ⚓ back', (await txt()).includes('⚓ PreToolUse hook (project/lint-guard)'));
  // select the failed test block via keys: it is selected after the click
  const modes = [];
  for (let i = 0; i < 3; i++) { await p.keyboard.press('e'); await sleep(30); modes.push((await txt()).match(/e fold: (\w+)/)[1]); }
  ok('e cycles 3 modes ' + modes.join('>'), modes.join() === 'truncated,expanded,collapsed');
  await p.keyboard.press('e'); await sleep(30);
  ok('truncated shows ⋮ hint and no $ row', (await txt()).includes('⋮ 4 more lines') && !(await txt()).includes('$ go test'));
  await p.keyboard.press('e'); await p.keyboard.press('e'); await p.keyboard.press('Tab');
  await p.keyboard.type('fix the test as well'); await p.keyboard.press('Enter'); await sleep(1500);
  ok('prompt streams blocks', /Thinking…|Working…/.test(await txt()));
  const pane = await p.evaluate(() => { const q = [...document.querySelectorAll('#term .r')].find(r => r.textContent.includes('Working…')).getBoundingClientRect(); return {x: q.x, y: q.y}; });
  await p.mouse.move(pane.x + 50, pane.y - 120); await p.mouse.wheel({deltaY: -300}); await sleep(100);
  ok('scroll up shows bottom marker', /▼ (\d+ new lines · )?End/.test(await txt()));
  await sleep(1200);
  ok('new output marker', (await txt()).match(/▼ \d+ new lines · End/) !== null);
  const bb = await p.evaluate(() => { const e = [...document.querySelectorAll('#term .r')].find(r => r.dataset.marker); const q = e.getBoundingClientRect(); return {x: q.right - 40, y: q.y + q.height / 2}; }); await p.mouse.click(bb.x, bb.y); await sleep(100);
  ok('click marker returns to bottom', !/▼ (\d+ new lines · )?End/.test(await txt()) && (await p.evaluate(() => askProto.state.follow)));
  await sleep(14000);
  ok('run ends with reply', (await txt()).includes('shall I fix') && !(await txt()).includes('Working…'));
  await p.click('#s120'); await sleep(50);
  ok('120x40 has 40 rows', (await p.$$eval('#term .r', x => x.length)) === 40);
  await p.click('#bexit'); await sleep(50);
  ok('exit line', (await txt()).includes('ask: session 3f2a9c1e · 3 turns · resume: ask --resume 3f2a9c1e'));
  await p.click('#breset'); await p.click('#s80'); await sleep(50);
  await p.screenshot({path: '/tmp/interactive.png'});
  console.log('page errors:', errs.length ? errs : 'none');
  await b.close();
})();
